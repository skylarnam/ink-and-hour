import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { join, extname } from 'node:path';
import { projectFile } from './store.mjs';

const escape = (value) => String(value).replace(/[&<>"']/g, (character) => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
})[character]);
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');

export async function renderReview(root, catalog) {
  const styles = [];
  const rows = [];
  const notices = [];
  for (const [index, candidate] of catalog.candidates.entries()) {
    const bytes = await readFile(projectFile(root, candidate.fontFile));
    const license = await readFile(projectFile(root, candidate.licenseFile));
    if (digest(bytes) !== candidate.fontSha256 || digest(license) !== candidate.licenseSha256) {
      throw new Error(`The source or license checksum changed for ${candidate.label}.`);
    }
    const face = `ReviewFace${index + 1}`;
    notices.push(`<h3>${escape(candidate.label)}</h3><pre>${escape(license.toString('utf8'))}</pre>`);
    const opentype = extname(candidate.fontFile) === '.otf';
    styles.push(`@font-face { font-family: "${face}"; src: url("data:font/${opentype ? 'otf' : 'ttf'};base64,${bytes.toString('base64')}") format("${opentype ? 'opentype' : 'truetype'}"); font-weight: 400; font-style: normal; font-display: block; }`);
    rows.push(`<section class="candidate" data-id="${escape(candidate.id)}" data-label="${escape(candidate.label)}" data-face="${face}" data-font-status="loading" data-selected="false">
  <input type="checkbox" id="pick-${candidate.id}" aria-label="Select ${escape(candidate.label)}" disabled>
  <span class="number">${String(index + 1).padStart(3, '0')}</span>
  <div class="font-name"><label for="pick-${candidate.id}">${escape(candidate.label)}</label><small>${candidate.current ? 'Current / ' : ''}<a href="${escape(candidate.source)}" target="_blank" rel="noopener noreferrer">${escape(candidate.license)}</a></small></div>
  <span class="sample" style="font-family: '${face}'">${escape(catalog.sample)}</span>
</section>`);
  }
  const css = await readFile(join(root, 'font-review/review.css'), 'utf8');
  const script = await readFile(join(root, 'font-review/review.js'), 'utf8');
  return `<!doctype html>
<!-- Generated by scripts/build-font-review.mjs. Choices live in selection.json. -->
<html lang="en">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="review-token" content="">
<title>Ink &amp; Hour - 100 handwriting candidates</title><style>${css}\n${styles.join('\n')}</style></head>
<body>
<header><p class="eyebrow">Ink &amp; Hour / font shortlist</p><h1>Find your handwriting.</h1>
<p class="intro">${catalog.candidates.length} candidates, including all ${catalog.candidates.filter(({ current }) => current).length} currently applied styles. Check only the ones you like. Changing these checkboxes does not change the website; applying a new selection requires your approval.</p>
<div class="toolbar"><span id="selection-count" aria-live="polite">0 selected</span><span id="font-count">Loading fonts...</span><button type="button" id="download-selection">Download selections</button></div>
<p id="save-status" role="status" aria-live="polite">Opening checklist...</p></header>
<main aria-label="100 handwriting candidates">${rows.join('\n')}</main>
<footer>These are original font previews, not animated pen strokes. All candidates allow commercial use under the listed licenses.<br>In the app panel, every checkbox is saved to <code>font-review/selection.json</code>. The live website uses the separately approved <code>font-review/applied-selection.json</code> snapshot; saved checkboxes are preserved.
<details class="license-notices"><summary>Font licenses and copyright notices</summary>${notices.join('\n')}</details></footer>
<script id="initial-selection" type="application/json">{}</script>
<script>${script.replaceAll('</script', '<\\/script')}</script>
</body></html>
`;
}
