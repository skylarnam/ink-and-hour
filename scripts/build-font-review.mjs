import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { readCatalog, ReviewStore } from '../font-review/store.mjs';
import { renderReview } from '../font-review/render.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = join(root, 'font-review/index.html');
try {
  const existing = await readFile(output, 'utf8');
  if (!existing.includes('Generated by scripts/build-font-review.mjs.')) {
    throw new Error('The existing font review is not a generated file; it has been preserved.');
  }
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
}
const catalog = await readCatalog(root);
await writeFile(output, await renderReview(root, catalog), 'utf8');
await new ReviewStore(root).read();
console.log(`Created ${output} with ${catalog.candidates.length} local font samples. Existing selections were preserved.`);
